export type { Messages };

export const resolveLanguage = (preference: Preferences["language"]): "en" | "ja" => {
  if (preference === "ja" || preference === "en") return preference;
  return navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
};

export const messages = (preference: Preferences["language"]): typeof en | typeof ja =>
  resolveLanguage(preference) === "ja" ? ja : en;
